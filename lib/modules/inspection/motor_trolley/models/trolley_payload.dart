/// A motor trolley inspection as the server takes it: the answers given,
/// under the server's names, readings as numbers. A question left blank is
/// left out, for the server to take or refuse; nothing is made up.
abstract final class TrolleyInspectionPayload {
  static Map<String, dynamic> build(MotorTrolleyInspectionState form) {
    final date = form.inspectionDate;
    return {
      if (date != null)
        'inspection_date': DateFormat('yyyy-MM-dd').format(date),
      for (final MapEntry(key: key, value: (name, number)) in _fields.entries)
        name: ?_value(form.value(key), number: number),
    };
  }

  static Object? _value(String? answer, {required bool number}) {
    final text = answer?.trim() ?? '';
    if (text.isEmpty) return null;
    return number ? double.tryParse(text) : text;
  }
}
